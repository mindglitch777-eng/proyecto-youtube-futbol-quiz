#!/usr/bin/env python3
"""
DESPERTADOR (19/11, pedido del CEO: "más autónomo, más eficiente, sin perder las olas"). Sin IA, corre cada 2 h (vigilancia.yml).
Arma la LISTA DE TAREAS del agente IA (datos/tareas_ia.json). El agente pasa 2 veces por día: si la lista está vacía termina en
segundos (casi no gasta); si hay algo, lo hace en el momento. La IA trabaja SOLO cuando hay algo que vale la pena.

Tareas (prioridad 1 = primero):
 1 ALARMA      alarma de sistema/subida abierta hace más de 2 h (la vigilancia sola no pudo).
 1 CEO         el CEO comentó en una propuesta o abrió una consulta y nadie le respondió todavía.
 2 OLA         la investigación diaria encontró un fuera de serie FUERTE que encaja con nuestra lógica y se hace con código
               (≥8x su canal, encaje ≥4, código ≥4, de los últimos 3 días): construir el formato YA, como propuesta con muestra.
 3 RECAMBIO    pocos formatos fuertes en rotación (<4 que rinden ≥1,5x el canal) o uno fijo cansado: construir un recambio
               (máximo una vez cada 3 días).
 3 SEMANA      lunes: mensaje semanal al CEO + hallazgos de analisis_ia.json (una vez por semana).
Lo hecho lo marca el agente en datos/tareas_hechas.json ({id: fecha}); el despertador no vuelve a pedir lo mismo.
Uso: python3 pipeline/despertador.py
"""
import json
import subprocess
from datetime import datetime, timedelta, timezone

from comun import CONFIG, RAIZ, cargar, guardar

ART = timezone(timedelta(hours=-3))
REPO = "mindglitch777-eng/proyecto-youtube-futbol-quiz"
DUENO = "mindglitch777-eng"


def gh(ruta):
    try:
        r = subprocess.run(["gh", "api", ruta], capture_output=True, text=True, cwd=RAIZ, timeout=60)
        return json.loads(r.stdout or "null")
    except Exception:
        return None


def main():
    ahora = datetime.now(ART); hoy = ahora.date()
    hechas = cargar("tareas_hechas.json", {})
    tareas = []

    def pedir(id_, prioridad, tipo, que, **datos):
        if id_ not in hechas:
            tareas.append(dict(id=id_, prioridad=prioridad, tipo=tipo, que=que, **datos))

    # 1. Alarmas y CEO (Issues)
    iss = gh(f"repos/{REPO}/issues?state=open&per_page=50") or []
    for i in iss:
        if "pull_request" in i:
            continue
        et = [x["name"] for x in i.get("labels", [])]
        creado = datetime.fromisoformat(i["created_at"].replace("Z", "+00:00"))
        if any(e in et for e in ("alerta-sistema", "alerta-subida")) and datetime.now(timezone.utc) - creado > timedelta(hours=2):
            pedir(f"alarma-{i['number']}-{hoy}", 1, "ALARMA", f"Alarma abierta hace más de 2 h: #{i['number']} {i['title']}. Diagnosticar la causa y arreglarla.",
                  issue=i["number"])
        if "propuesta" in et or "consulta" in et:
            ult = (gh(f"repos/{REPO}/issues/{i['number']}/comments?per_page=100") or [])[-1:]
            quien = ult[0]["user"]["login"] if ult else i["user"]["login"]
            cuando = ult[0]["created_at"] if ult else i["created_at"]
            cuerpo = (ult[0]["body"] if ult else "") or ""
            if quien == DUENO and "Generated by [Claude Code]" not in cuerpo:
                pedir(f"ceo-{i['number']}-{cuando}", 1, "CEO", f"El CEO respondió/preguntó en #{i['number']} ({i['title']}): ejecutar lo que decidió o responderle.",
                      issue=i["number"])

    # 2. Olas: fuera de serie fuertes de la investigación diaria
    d = cargar("dossier.json", {})
    for x in d.get("ideas", []):
        if (x.get("ratio") or 0) >= 8 and (x.get("encaja_con_nuestra_logica") or 0) >= 4 and (x.get("replicable_con_codigo") or 0) >= 4 \
                and d.get("fecha", "") >= (hoy - timedelta(days=3)).isoformat():
            pedir(f"ola-{x['id']}", 2, "OLA", f"Ola: «{x.get('nombre_formato')}» hizo {x['vistas']:,} vistas ({x['ratio']}x su canal). "
                  f"Construir NUESTRA versión ya (propuesta con muestra): {x.get('idea_para_nosotros')}",
                  video=f"https://www.youtube.com/shorts/{x['id']}")
            break                                                              # una ola por vez: calidad antes que cantidad

    # 3. Recambio: ¿cuántos formatos fuertes hay en rotación?
    cer = cargar("cerebro.json", {}).get("formatos", {})
    g = cargar("gerente.json", {})
    med = ((g.get("salud") or {}).get("poda") or {}).get("mediana_canal") or 0
    activos = {k for k, v in CONFIG["pruebas"].items() if v.get("listo")} | {"rueda", "cabezas"}
    fuertes = [k for k, x in cer.items() if k in activos and med and (x.get("mediana_48h") or 0) >= 1.5 * med and x.get("videos", 0) >= 2]
    cansados = [c["formato"] for c in g.get("cansados") or []]
    ult_rec = max((v for k, v in hechas.items() if k.startswith("recambio-")), default="")
    if (len(fuertes) < 4 or cansados) and ult_rec < (hoy - timedelta(days=3)).isoformat():
        pedir(f"recambio-{hoy}", 3, "RECAMBIO", f"Hay {len(fuertes)} formatos fuertes en rotación ({', '.join(fuertes) or 'ninguno'})"
              + (f" y se cansan {', '.join(cansados)}" if cansados else "") + ". Construir un formato nuevo de la misma lógica "
              "(elegir entre superestrellas + parar justo), más difícil o con otra vuelta, como propuesta con muestra. Mirar primero el informe "
              "(reports/dossier/) por ideas.", fuertes=fuertes, cansados=cansados)

    # 4. Lunes: mensaje semanal
    lunes = hoy - timedelta(days=hoy.weekday())
    if hoy.weekday() == 0 or f"semana-{lunes}" not in hechas:
        if ahora.hour >= 10:
            pedir(f"semana-{lunes}", 3, "SEMANA", "Mensaje semanal al CEO (estrategia.md sección 00) y actualizar los hallazgos de pipeline/datos/analisis_ia.json.")

    tareas.sort(key=lambda t: t["prioridad"])
    out = dict(fecha=ahora.strftime("%Y-%m-%d %H:%M"), tareas=tareas)
    guardar("tareas_ia.json", out)
    print(f"{len(tareas)} tareas para la IA:", *[f"[{t['prioridad']}] {t['tipo']}: {t['que'][:110]}" for t in tareas], sep="\n")
    return out


if __name__ == "__main__":
    main()
